import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { renderScoop } from '../scripts/render-scoop.mjs';

const ZIP = 'a'.repeat(64);
const SETUP = 'b'.repeat(64);
const sums = {
  'canvas-0.4.0-windows-x64.zip': ZIP,
  'canvas-0.4.0-linux-x64.tar.gz': 'c'.repeat(64),
  'canvas-app-0.4.0-windows-x64-setup.exe': SETUP,
  'canvas-app-0.4.0-windows-x64.msi': 'd'.repeat(64),
};
const manifest = (name, base) => JSON.parse(renderScoop(name, '0.4.0', sums, base));

test('canvas is the release zip with bin\\canvas.exe', () => {
  const m = manifest('canvas');
  assert.equal(m.version, '0.4.0');
  assert.equal(m.license, 'MIT');
  assert.equal(m.bin, 'bin\\canvas.exe');
  assert.deepEqual(m.architecture, { '64bit': { url: 'https://github.com/hyperlab-sh/canvas/releases/download/v0.4.0/canvas-0.4.0-windows-x64.zip', hash: ZIP } });
  assert.equal(m.depends, undefined);
});

test('canvas-app runs the NSIS setup into the app directory and depends on canvas', () => {
  const m = manifest('canvas-app');
  assert.equal(m.depends, 'hyperlab/canvas');
  assert.deepEqual(m.architecture, { '64bit': { url: 'https://github.com/hyperlab-sh/canvas/releases/download/v0.4.0/canvas-app-0.4.0-windows-x64-setup.exe', hash: SETUP } });
  assert.deepEqual(m.installer, { file: 'canvas-app-0.4.0-windows-x64-setup.exe', args: ['/S', '/D=$dir'] });
  assert.deepEqual(m.uninstaller, { file: 'uninstall.exe', args: ['/S', '_?=$dir'] });
  assert.equal(m.bin, undefined);
});

test('/D= is the last installer argument (NSIS ignores anything after it)', () => {
  assert.match(manifest('canvas-app').installer.args.at(-1), /^\/D=/);
});

test('the output is 4-space JSON with a trailing newline and a generated-file notice', () => {
  const text = renderScoop('canvas', '0.4.0', sums);
  assert.ok(text.endsWith('}\n'));
  assert.match(text, /^ {4}"##": "Generated by scripts\/render-scoop\.mjs/m);
});

test('--base replaces the download base', () => {
  assert.equal(manifest('canvas', 'http://127.0.0.1:8000').architecture['64bit'].url, 'http://127.0.0.1:8000/canvas-0.4.0-windows-x64.zip');
  assert.equal(manifest('canvas-app', 'http://127.0.0.1:8000').architecture['64bit'].url, 'http://127.0.0.1:8000/canvas-app-0.4.0-windows-x64-setup.exe');
});

test('a missing asset is refused, naming the file', () => {
  const { 'canvas-0.4.0-windows-x64.zip': _, ...noZip } = sums;
  assert.throws(() => renderScoop('canvas', '0.4.0', noZip), /canvas-0\.4\.0-windows-x64\.zip is not in SHA256SUMS/);
  const { 'canvas-app-0.4.0-windows-x64-setup.exe': __, ...noSetup } = sums;
  assert.throws(() => renderScoop('canvas-app', '0.4.0', noSetup), /canvas-app-0\.4\.0-windows-x64-setup\.exe is not in SHA256SUMS/);
});

test('sums of another version do not satisfy the manifest', () => {
  assert.throws(() => renderScoop('canvas', '0.5.0', sums), /canvas-0\.5\.0-windows-x64\.zip is not in/);
});

test('an unknown package is refused', () => {
  assert.throws(() => renderScoop('nope', '0.4.0', sums), /unknown package "nope"/);
});

test('the command line reads a release directory and --base', () => {
  const dir = mkdtempSync(join(tmpdir(), 'render-scoop-'));
  try {
    writeFileSync(join(dir, 'SHA256SUMS'), Object.entries(sums).map(([name, hash]) => `${hash}  ${name}`).join('\n') + '\n');
    const script = new URL('../scripts/render-scoop.mjs', import.meta.url).pathname;
    const out = execFileSync(process.execPath, [script, 'canvas-app', '0.4.0', dir, '--base', 'http://localhost:1'], { encoding: 'utf8' });
    assert.equal(out, renderScoop('canvas-app', '0.4.0', sums, 'http://localhost:1'));
  } finally {
    rmSync(dir, { recursive: true });
  }
});
