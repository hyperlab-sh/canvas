// Prints a Scoop manifest for a release from its SHA256SUMS.
//   node scripts/render-scoop.mjs <canvas|canvas-app> <version> <release-dir|SHA256SUMS> [--base <download base url>]
// `canvas` is the CLI and service (the release zip, `bin\canvas.exe`); `canvas-app` is the desktop app (the NSIS setup, which
// depends on `canvas`; its version is the app's, as for the cask). The tap (hyperlab-sh/homebrew-tap) keeps the output as
// bucket/<name>.json; the release workflow pushes it there.
import { readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assetName } from './app-assets.mjs';
import { parseSums } from './render-cask.mjs';

const REPO = 'https://github.com/hyperlab-sh/canvas';
const BUCKET = 'hyperlab';

/** The manifest text for package `name` at `version`; `sums` maps release asset names to their sha256. */
export function renderScoop(name, version, sums, base = `${REPO}/releases/download/v${version}`, sumsFile = 'SHA256SUMS') {
  const asset = (file) => {
    if (!sums[file]) throw new Error(`${file} is not in ${sumsFile}`);
    return { url: `${base}/${file}`, hash: sums[file] };
  };
  const common = { '##': 'Generated by scripts/render-scoop.mjs in hyperlab-sh/canvas; do not edit by hand.', version, homepage: REPO, license: 'MIT' };
  let manifest;
  if (name === 'canvas') {
    manifest = {
      ...common,
      description: 'Local diagram service for coding agents, with a canvas editor and MCP server',
      architecture: { '64bit': asset(`canvas-${version}-windows-x64.zip`) },
      // bin\canvas.exe finds its app and server in ..\share\canvas, so the zip stays together in the app directory.
      bin: 'bin\\canvas.exe',
    };
  } else if (name === 'canvas-app') {
    manifest = {
      ...common,
      description: 'Native window for the Canvas diagram editor',
      // The app is only a window onto the service the canvas package installs.
      depends: `${BUCKET}/canvas`,
      architecture: { '64bit': asset(assetName(version, 'windows-x64', '-setup.exe')) },
      // The NSIS setup installs into the Scoop app directory (/D must come last) and leaves its own uninstall.exe there.
      // `_?=` makes the uninstaller run in place and wait, so Scoop does not remove the directory under it.
      installer: { file: assetName(version, 'windows-x64', '-setup.exe'), args: ['/S', '/D=$dir'] },
      uninstaller: { file: 'uninstall.exe', args: ['/S', '_?=$dir'] },
    };
  } else {
    throw new Error(`unknown package "${name}"; one of: canvas, canvas-app`);
  }
  return `${JSON.stringify(manifest, null, 4)}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [name, version, source, ...rest] = process.argv.slice(2);
  if (!name || !version || !source) throw new Error('usage: render-scoop.mjs <canvas|canvas-app> <version> <release-dir|SHA256SUMS> [--base <url>]');
  const baseIndex = rest.indexOf('--base');
  const sumsFile = statSync(source).isDirectory() ? join(source, 'SHA256SUMS') : source;
  process.stdout.write(renderScoop(name, version, parseSums(readFileSync(sumsFile, 'utf8')), baseIndex >= 0 ? rest[baseIndex + 1] : undefined, sumsFile));
}
