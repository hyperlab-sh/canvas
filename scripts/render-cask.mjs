// Prints the Homebrew cask for the desktop app of a release from its SHA256SUMS.
//   node scripts/render-cask.mjs <app version> <release-dir|SHA256SUMS> [--base <download base url>]
// The tap (hyperlab-sh/homebrew-tap) keeps the output as Casks/canvas-app.rb; the release workflow pushes it there.
import { readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assetName } from './app-assets.mjs';

/** The cask text for `version`; `sums` maps release asset names to their sha256. */
export function renderCask(version, sums, base = `https://github.com/hyperlab-sh/canvas/releases/download/v${version}`, sumsFile = 'SHA256SUMS') {
  const dmg = (cpu) => {
    const name = assetName(version, `darwin-${cpu}`, 'dmg');
    if (!sums[name]) throw new Error(`${name} is not in ${sumsFile}`);
    return sums[name];
  };
  return `# Generated by scripts/render-cask.mjs in hyperlab-sh/canvas; do not edit by hand.
cask "canvas-app" do
  arch arm: "arm64", intel: "x64"

  version "${version}"
  sha256 arm:   "${dmg('arm64')}",
         intel: "${dmg('x64')}"

  url "${base}/canvas-app-#{version}-darwin-#{arch}.dmg"
  name "Canvas"
  desc "Native window for the Canvas diagram editor"
  homepage "https://github.com/hyperlab-sh/canvas"

  # The app is only a window onto the service the formula installs.
  depends_on formula: "hyperlab-sh/tap/canvas"
  # Keeps Linuxbrew out. Not a floor: Homebrew supports only recent macOS and rejects the old minimum versions.
  depends_on :macos

  app "Canvas.app"

  # The app is not signed or notarized (no Apple Developer account), so Gatekeeper would refuse the quarantined copy.
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/Canvas.app"]
  end

  zap trash: [
    "~/Library/Application Support/sh.hyperlab.canvas",
    "~/Library/Caches/sh.hyperlab.canvas",
    "~/Library/Preferences/sh.hyperlab.canvas.plist",
    "~/Library/Saved Application State/sh.hyperlab.canvas.savedState",
    "~/Library/WebKit/sh.hyperlab.canvas",
  ]
end
`;
}

export function parseSums(text) {
  return Object.fromEntries(text.trim().split('\n').map((line) => { const [hash, name] = line.split(/\s+/); return [name, hash]; }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [version, source, ...rest] = process.argv.slice(2);
  if (!version || !source) throw new Error('usage: render-cask.mjs <app version> <release-dir|SHA256SUMS> [--base <url>]');
  const baseIndex = rest.indexOf('--base');
  const sumsFile = statSync(source).isDirectory() ? join(source, 'SHA256SUMS') : source;
  process.stdout.write(renderCask(version, parseSums(readFileSync(sumsFile, 'utf8')), baseIndex >= 0 ? rest[baseIndex + 1] : undefined, sumsFile));
}
