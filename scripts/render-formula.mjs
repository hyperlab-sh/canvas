// Prints the Homebrew formula for a release from its SHA256SUMS.
//   node scripts/render-formula.mjs <version> <release-dir|SHA256SUMS> [--base <download base url>]
// The tap (hyperlab-sh/homebrew-tap) keeps the output as Formula/canvas.rb; the release workflow pushes it there.
import { readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const [version, source, ...rest] = process.argv.slice(2);
if (!version || !source) throw new Error('usage: render-formula.mjs <version> <release-dir|SHA256SUMS> [--base <url>]');
const baseIndex = rest.indexOf('--base');
const base = baseIndex >= 0 ? rest[baseIndex + 1] : `https://github.com/hyperlab-sh/canvas/releases/download/v${version}`;
const sumsFile = statSync(source).isDirectory() ? join(source, 'SHA256SUMS') : source;
const sums = Object.fromEntries(readFileSync(sumsFile, 'utf8').trim().split('\n').map((line) => { const [hash, name] = line.split(/\s+/); return [name, hash]; }));

function platform(os, cpu) {
  const name = `canvas-${version}-${os}-${cpu}.tar.gz`;
  if (!sums[name]) throw new Error(`${name} is not in ${sumsFile}`);
  return `    url "${base}/${name}"\n    sha256 "${sums[name]}"`;
}

process.stdout.write(`# Generated by scripts/render-formula.mjs in hyperlab-sh/canvas; do not edit by hand.
class Canvas < Formula
  desc "Local diagram service for coding agents, with a canvas editor and MCP server"
  homepage "https://github.com/hyperlab-sh/canvas"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${platform('darwin', 'arm64').replace(/^/gm, '  ')}
    end
    on_intel do
${platform('darwin', 'x64').replace(/^/gm, '  ')}
    end
  end

  on_linux do
    on_arm do
${platform('linux', 'arm64').replace(/^/gm, '  ')}
    end
    on_intel do
${platform('linux', 'x64').replace(/^/gm, '  ')}
    end
  end

  def install
    # bin/canvas finds its app and server in ../share/canvas, so the archive stays together in libexec.
    libexec.install "bin", "share"
    bin.install_symlink libexec/"bin/canvas"
    prefix.install "LICENSE", "NOTICE"
  end

  def caveats
    # The cask is macOS-only, so Linux users are not pointed at it.
    app = OS.mac? ? "The desktop app is a separate cask:\\n  brew install --cask hyperlab-sh/tap/canvas-app\\n" : ""
    app + <<~EOS
      Keep it running in the background (and at every login):
        canvas service install
      The service points at #{opt_libexec}/bin/canvas, so \`brew upgrade canvas\` keeps it working.
    EOS
  end

  test do
    assert_match "canvas", shell_output("#{bin}/canvas --help")
    (testpath/"a.mmd").write "graph LR\\n  A-->B\\n"
    system bin/"canvas", "render", "a.mmd", "-o", "a.svg"
    assert_match "<svg", (testpath/"a.svg").read
  end
end
`);
