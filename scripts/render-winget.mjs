// Writes the winget manifests for a release from its SHA256SUMS, in the layout of microsoft/winget-pkgs.
//   node scripts/render-winget.mjs <canvas|canvas-app> <version> <release-dir|SHA256SUMS> --out <dir>
// `canvas` is Hyperlab.Canvas (the release zip as a portable); `canvas-app` is Hyperlab.CanvasApp (the MSI, which depends on it).
// CI validates the files with `winget validate` and uploads them; the pull request to microsoft/winget-pkgs is opened by hand.
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assetName } from './app-assets.mjs';
import { parseSums } from './render-cask.mjs';

const REPO = 'https://github.com/hyperlab-sh/canvas';
const MANIFEST_VERSION = '1.6.0';
const GENERATED = '# Generated by scripts/render-winget.mjs in hyperlab-sh/canvas; do not edit by hand.';
const SCHEMA = (type) => `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${MANIFEST_VERSION}.schema.json`;

const PACKAGES = {
  canvas: {
    id: 'Hyperlab.Canvas',
    moniker: 'canvas',
    shortDescription: 'Local diagram service for coding agents, with a canvas editor and MCP server',
    tags: ['diagram', 'mcp', 'agents', 'mermaid'],
  },
  'canvas-app': {
    id: 'Hyperlab.CanvasApp',
    moniker: 'canvas-app',
    shortDescription: 'Native window for the Canvas diagram editor',
    tags: ['diagram', 'editor', 'mermaid'],
  },
};

/** The manifest files of package `name` at `version` as { relative path: text }; `sums` maps release asset names to their sha256. */
export function renderWinget(name, version, sums, sumsFile = 'SHA256SUMS') {
  const base = `${REPO}/releases/download/v${version}`;
  const pkg = PACKAGES[name];
  if (!pkg) throw new Error(`unknown package "${name}"; one of: ${Object.keys(PACKAGES).join(', ')}`);
  const asset = name === 'canvas' ? `canvas-${version}-windows-x64.zip` : assetName(version, 'windows-x64', 'msi');
  if (!sums[asset]) throw new Error(`${asset} is not in ${sumsFile}`);
  const sha256 = sums[asset].toUpperCase();
  const [publisher, packageName] = pkg.id.split('.');
  const head = (type) => `${GENERATED}\n${SCHEMA(type)}\n\nPackageIdentifier: ${pkg.id}\nPackageVersion: ${version}\n`;
  const tail = (type) => `ManifestType: ${type}\nManifestVersion: ${MANIFEST_VERSION}\n`;

  const installerBody = name === 'canvas'
    ? `InstallerLocale: en-US
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
- RelativeFilePath: bin\\canvas.exe
  PortableCommandAlias: canvas
Installers:
- Architecture: x64
  InstallerUrl: ${base}/${asset}
  InstallerSha256: ${sha256}
`
    : `InstallerLocale: en-US
InstallerType: wix
Scope: machine
Installers:
- Architecture: x64
  InstallerUrl: ${base}/${asset}
  InstallerSha256: ${sha256}
Dependencies:
  PackageDependencies:
  - PackageIdentifier: Hyperlab.Canvas
`;

  const locale = `PackageLocale: en-US
Publisher: Hyperlab
PublisherUrl: https://github.com/hyperlab-sh
PackageName: Canvas
PackageUrl: ${REPO}
License: MIT
LicenseUrl: ${REPO}/blob/main/LICENSE
ShortDescription: ${pkg.shortDescription}
Moniker: ${pkg.moniker}
Tags:
${pkg.tags.map((tag) => `- ${tag}`).join('\n')}
`;

  const dir = `manifests/${publisher[0].toLowerCase()}/${publisher}/${packageName}/${version}`;
  return {
    [`${dir}/${pkg.id}.yaml`]: `${head('version')}DefaultLocale: en-US\n${tail('version')}`,
    [`${dir}/${pkg.id}.installer.yaml`]: `${head('installer')}${installerBody}${tail('installer')}`,
    [`${dir}/${pkg.id}.locale.en-US.yaml`]: `${head('defaultLocale')}${locale}${tail('defaultLocale')}`,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [name, version, source, ...rest] = process.argv.slice(2);
  const option = (flag) => (rest.includes(flag) ? rest[rest.indexOf(flag) + 1] : undefined);
  const out = option('--out');
  if (!name || !version || !source || !out) throw new Error('usage: render-winget.mjs <canvas|canvas-app> <version> <release-dir|SHA256SUMS> --out <dir>');
  const sumsFile = statSync(source).isDirectory() ? join(source, 'SHA256SUMS') : source;
  for (const [file, text] of Object.entries(renderWinget(name, version, parseSums(readFileSync(sumsFile, 'utf8')), sumsFile))) {
    mkdirSync(join(out, file, '..'), { recursive: true });
    writeFileSync(join(out, file), text);
    console.log(file);
  }
}
